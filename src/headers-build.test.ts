import { createHash } from 'node:crypto';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { generateHeadersFile } from '../scripts/build-headers.mjs';

// The header generator is build infrastructure that has to keep working
// across the upcoming rewrites — these tests pin its security contracts:
// every inline script is hash-pinned (so script-src never needs
// 'unsafe-inline') and the _headers file carries the baseline rules.

let fixtureDir: string;

beforeEach(() => {
  fixtureDir = mkdtempSync(join(tmpdir(), 'padify-headers-'));
});

afterEach(() => {
  rmSync(fixtureDir, { recursive: true, force: true });
});

function writeEntry(html: string): void {
  writeFileSync(join(fixtureDir, 'index.html'), html);
}

describe('inline script pinning', () => {
  it('hashes every inline script and pins it in script-src', () => {
    const first = "document.body.classList.add('dark');";
    const second = 'window.__boot = 1;';
    writeEntry(
      `<html><body><script>${first}</script>` +
        `<script type="module" src="/assets/main.js"></script>` +
        `<script>${second}</script></body></html>`,
    );

    const build = generateHeadersFile(fixtureDir);

    const expectedFirst = `'sha256-${createHash('sha256').update(first, 'utf8').digest('base64')}'`;
    const expectedSecond = `'sha256-${createHash('sha256').update(second, 'utf8').digest('base64')}'`;
    expect(build.scriptHashes).toEqual([expectedFirst, expectedSecond]);
    expect(build.csp).toContain(`script-src 'self' ${expectedFirst} ${expectedSecond}`);
  });

  it('never falls back to unsafe-inline, with or without inline scripts', () => {
    writeEntry('<html><body><script type="module" src="/assets/main.js"></script></body></html>');

    const build = generateHeadersFile(fixtureDir);

    expect(build.scriptHashes).toEqual([]);
    expect(build.csp).toContain("script-src 'self'");
    // script-src must stay free of inline execution — that is the point.
    const scriptSrc = build.csp.match(/script-src [^;]*/)![0];
    expect(scriptSrc).not.toContain('unsafe-inline');
    // …while inline styles stay allowed (features style the DOM directly).
    expect(build.csp).toContain("style-src 'self' 'unsafe-inline'");
  });

  it('refuses to run against a missing build', () => {
    expect(() => generateHeadersFile(fixtureDir)).toThrow(/vite build/i);
  });
});

describe('the headers file', () => {
  it('carries the baseline rules for every path and the sw.js exception', () => {
    writeEntry('<html><body><script>0;</script></body></html>');

    const { headersFile } = generateHeadersFile(fixtureDir);

    expect(headersFile).toContain('/*\n  X-Content-Type-Options: nosniff');
    expect(headersFile).toContain('Referrer-Policy: strict-origin-when-cross-origin');
    expect(headersFile).toContain('Strict-Transport-Security: max-age=63072000');
    expect(headersFile).toContain('X-Frame-Options: DENY');
    expect(headersFile).toContain('Content-Security-Policy: ');
    expect(headersFile).toContain('/sw.js\n  Cache-Control: public, max-age=0, must-revalidate');
  });
});

describe('API origin (VITE_API_BASE)', () => {
  it('defaults to same-origin: no proxy redirect, empty share apiBase, no extra connect-src origin', () => {
    writeEntry('<html><body><script>0;</script></body></html>');

    const build = generateHeadersFile(fixtureDir);

    expect(build.apiBase).toBe('');
    // No _redirects file without an API origin to proxy to.
    expect(build.redirectsFile).toBeNull();
    // The share viewer template stays at the same-origin default.
    expect(build.shareConfigFile).toContain("apiBase: ''");
    expect(build.shareConfigFile).toContain('GENERATED by scripts/build-headers.mjs');
    // connect-src admits only self.
    expect(build.csp).toContain("connect-src 'self'");
  });

  it('bakes ONE origin into the CSP, the share config and the proxy redirect', () => {
    writeEntry('<html><body><script>0;</script></body></html>');

    const build = generateHeadersFile(fixtureDir, { apiBase: 'https://api.example.com' });

    expect(build.apiBase).toBe('https://api.example.com');
    expect(build.csp).toContain("connect-src 'self' https://api.example.com");
    expect(build.shareConfigFile).toContain("apiBase: 'https://api.example.com'");
    expect(build.redirectsFile).toContain('/api/*  https://api.example.com/:splat  200!');
  });

  it('normalizes a trailing slash away so fetch base and redirect target agree', () => {
    writeEntry('<html><body><script>0;</script></body></html>');

    const build = generateHeadersFile(fixtureDir, { apiBase: 'https://api.example.com/' });

    expect(build.apiBase).toBe('https://api.example.com');
    expect(build.redirectsFile).toContain('/api/*  https://api.example.com/:splat  200!');
  });

  it('bakes a path-bearing base into the share config, the proxy redirect and a CSP directory entry', () => {
    // Shared-domain hosts (alwaysdata & co.) can only hand out subpaths:
    // the API lives at https://host/padifyapi while the front proxy maps it
    // onto the domain. The CSP entry gains a trailing slash so path matching
    // admits every endpoint under the mount point, never just the prefix
    // string itself.
    writeEntry('<html><body><script>0;</script></body></html>');

    const build = generateHeadersFile(fixtureDir, {
      apiBase: 'https://functionhost.example.com/padifyapi/',
    });

    expect(build.apiBase).toBe('https://functionhost.example.com/padifyapi');
    expect(build.csp).toContain("connect-src 'self' https://functionhost.example.com/padifyapi/");
    expect(build.shareConfigFile).toContain(
      "apiBase: 'https://functionhost.example.com/padifyapi'",
    );
    expect(build.redirectsFile).toContain(
      '/api/*  https://functionhost.example.com/padifyapi/:splat  200!',
    );
  });

  it('fails the build on a malformed value instead of shipping parts that disagree', () => {
    writeEntry('<html><body><script>0;</script></body></html>');

    const malformed = [
      'api.example.com', // relative
      'https://api.example.com/v1?x=1', // query
      'https://api.example.com/#frag', // fragment
      'ftp://api.example.com', // not http(s)
      'https://', // no host
      'https://api.example.com//v1', // empty path segment
    ];
    for (const value of malformed) {
      expect(() => generateHeadersFile(fixtureDir, { apiBase: value })).toThrow(/VITE_API_BASE/);
    }
  });
});
