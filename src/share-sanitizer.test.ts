// @vitest-environment node
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { renderShareSanitizer } from '../scripts/build-share.mjs';

// The share viewer's sanitizer used to be a hand-copy of the app's, kept in
// sync by a comment — and public/ is outside ESLint, so hardening the app's
// copy silently diverged the one that renders SHARED notes to strangers.
// The copy is now GENERATED: scripts/build-share.mjs transforms
// src/editor/storage-subset.ts into public/share/sanitize-note.js.
//
// This suite runs in the Node environment (esbuild — which vite's
// transformWithEsbuild drives — refuses jsdom's patched globals); the
// behavioral twin of these tests, running the generated module against the
// canonical one over a hostile corpus in jsdom, lives in
// share-sanitizer.corpus.test.ts.

const GENERATED_PATH = resolve(process.cwd(), 'public/share/sanitize-note.js');

describe('the generated share sanitizer', () => {
  it('is exactly what build-share.mjs renders from storage-subset.ts', async () => {
    // Drift guard: hand edits to the generated file, or a source change
    // without re-running `npm run build:share`, fail here.
    const generated = await renderShareSanitizer();
    const checkedIn = readFileSync(GENERATED_PATH, 'utf-8');

    expect(checkedIn).toBe(generated);
  });

  it('carries the generated-file banner so nobody mistakes it for source', async () => {
    const checkedIn = readFileSync(GENERATED_PATH, 'utf-8');

    expect(checkedIn).toContain('GENERATED by scripts/build-share.mjs');
    expect(checkedIn).toContain('DO NOT EDIT');
  });

  it('exports the sanitizeNoteHtml entry the share page imports', async () => {
    const generated = await renderShareSanitizer();

    expect(generated).toContain('export');
    expect(generated).toContain('sanitizeNoteHtml');
  });
});
