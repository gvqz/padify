/**
 * Generates the share viewer's sanitizer from the app's canonical one.
 *
 * The public share page (public/share/) is a no-build static island: it
 * cannot import from src/. For years its sanitizer was a hand-copy of
 * sanitizeNoteHtml with a "Keep the two in sync" comment — and public/ is
 * excluded from ESLint, so every hardening of src/editor/storage-subset.ts
 * silently diverged the copy that renders SHARED notes to third parties.
 * (The copy had already fallen behind: it dropped math shells entirely, so
 * shared notes with equations rendered with the equations missing.)
 *
 * This script is the sync mechanism: it transforms the canonical
 * storage-subset.ts (pure functions, no imports) into the plain ES module
 * public/share/sanitize-note.js, which share.js imports. The checked-in
 * generated file is pinned by src/share-sanitizer.test.ts, which
 * regenerates it in memory and fails on any drift, and by a corpus test
 * that runs BOTH implementations over the same tricky inputs.
 *
 * Run: npm run build:share   (also runs as part of npm run build, BEFORE
 * vite build, because public/ is copied verbatim into the bundle)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { transformWithEsbuild } from 'vite';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE_PATH = join(here, '..', 'src', 'editor', 'storage-subset.ts');
export const OUTPUT_PATH = join(here, '..', 'public', 'share', 'sanitize-note.js');

const BANNER = `/**
 * The share viewer's note sanitizer.
 *
 * GENERATED by scripts/build-share.mjs from src/editor/storage-subset.ts —
 * DO NOT EDIT. Any change to the sanitizer policy belongs in the source
 * file; regenerate with \`npm run build:share\`. src/share-sanitizer.test.ts
 * fails the build when this copy drifts from its source.
 */
`;

/**
 * Renders the generated module's content. Exported so the drift test can
 * regenerate it in memory and compare against the checked-in file.
 *
 * @param {string} [source] — the storage-subset.ts source (read from disk
 *   when omitted).
 * @returns {Promise<string>} the full content of sanitize-note.js
 */
export async function renderShareSanitizer(source = readFileSync(SOURCE_PATH, 'utf-8')) {
  const { code } = await transformWithEsbuild(source, 'storage-subset.ts', {
    loader: 'ts',
    format: 'esm',
    // The share page's own scripts are ES2017-era vanilla; keep the
    // generated module in the same dialect.
    target: 'es2018',
  });
  return `${BANNER}${code.trim()}\n`;
}

// CLI entry point — skip when the module is imported (e.g. by vitest).
// No top-level await: it also keeps TypeScript's inference happy for the
// test file that imports this module (TLA needs a newer target than the
// repo's tsconfig).
if (process.argv[1] && process.argv[1].endsWith('build-share.mjs')) {
  void renderShareSanitizer().then((generated) => {
    writeFileSync(OUTPUT_PATH, generated);
    console.log(`[build-share] wrote ${OUTPUT_PATH} (${generated.length} bytes)`);
  });
}
