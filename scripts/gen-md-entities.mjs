/**
 * Generates src/editor/markdown/entities.generated.ts — the HTML5 named
 * character reference table the Markdown renderer decodes `&copy;`-style
 * references with.
 *
 * SOURCE OF TRUTH: the WHATWG entities.json (https://html.spec.whatwg.org/
 * entities.json) — the same table browsers and the CommonMark reference
 * implementation derive their entity sets from. CommonMark only recognises
 * references WITH the trailing semicolon, so the legacy semicolon-less
 * entries (`&AMP`, `&copy`) are dropped: `&copy` without `;` stays literal
 * text, exactly as the spec demands.
 *
 * The generated file is checked in — CI never touches the network. Re-run
 * this script only when the entity table itself needs a refresh:
 *
 *   node scripts/gen-md-entities.mjs
 */
import { writeFileSync } from 'node:fs';

const SOURCE_URL = 'https://html.spec.whatwg.org/entities.json';
const OUT = new URL('../src/editor/markdown/entities.generated.ts', import.meta.url);

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`entities.json fetch failed: ${response.status} ${response.statusText}`);
}
const table = await response.json();

const entries = Object.entries(table)
  .filter(([key]) => key.endsWith(';'))
  .map(([key, value]) => {
    const name = key.slice(1, -1); // strip & and ;
    const codepoints = value.codepoints;
    // String.fromCodePoint throws on lone surrogates — escape each
    // codepoint individually instead, the same way JSON does.
    const literal = codepoints.map((cp) => `\\u{${cp.toString(16)}}`).join('');
    return [name, literal];
  })
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const pairs = entries.map(([name, literal]) => `  '${name}': '${literal}',`).join('\n');

const banner = `/**
 * The HTML5 named character references, WITH the trailing semicolon —
 * GENERATED by scripts/gen-md-entities.mjs from the WHATWG entities.json
 * (${SOURCE_URL}). DO NOT EDIT.
 *
 * CommonMark recognises only semicolon-terminated named references, so the
 * spec's legacy semicolon-less entries are excluded: \`&copy\` without \`;\`
 * renders as the text it is. Values are per-codepoint escapes (no raw
 * literals) so the table survives any file encoding unchanged.
 */
`;

const out = `${banner}
export const NAMED_ENTITIES: Readonly<Record<string, string>> = Object.freeze({
${pairs}
});
`;

writeFileSync(OUT, out);
console.log(`[gen-md-entities] wrote ${OUT.pathname} (${entries.length} entities)`);
