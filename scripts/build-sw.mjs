/**
 * Post-build step: generates dist/sw.js with a precache manifest derived
 * from the actual build output, so hashed Vite assets are always cached.
 *
 * The generated service worker uses a cache-first strategy with network
 * fallback, mirroring the behavior of the original hand-written sw.js.
 */
import { createHash } from 'node:crypto';
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const distDir = new URL('../dist', import.meta.url).pathname;

if (!existsSync(distDir)) {
  console.error('[build-sw] dist/ not found. Run `vite build` first.');
  process.exit(1);
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stats = statSync(full);
    if (stats.isDirectory()) {
      out.push(...walk(full));
    } else {
      out.push(full);
    }
  }
  return out;
}

const files = walk(distDir)
  .map((full) => relative(distDir, full))
  .filter((file) => file !== 'sw.js')
  .sort();

const indexHtml = readFileSync(join(distDir, 'index.html'), 'utf8');

// Cache URLs are root-relative. Directories are served with a trailing
// slash by static hosts, so precache both spellings for the entry pages.
const precacheUrls = ['/', ...files.map((file) => `/${file.split('\\').join('/')}`)];

const hash = createHash('sha256')
  .update(precacheUrls.join('|'))
  .update(indexHtml)
  .digest('hex')
  .slice(0, 10);

const cacheVersion = `app-v${hash}`;

const swSource = `/* Generated by scripts/build-sw.mjs — do not edit by hand. */
const CACHE_VERSION = '${cacheVersion}';
const CACHE_FILES = ${JSON.stringify(precacheUrls, null, 4)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_VERSION).then((cache) => cache.addAll(CACHE_FILES))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key !== CACHE_VERSION).map((key) => caches.delete(key)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;

  if (request.method !== 'GET') {
    return;
  }

  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response && response.status === 200 && response.type === 'basic') {
          const cloned = response.clone();
          caches.open(CACHE_VERSION).then((cache) => cache.put(request, cloned));
        }
        return response;
      })
      .catch(() =>
        caches.match(request).then((cached) => cached || caches.match('/index.html'))
      )
  );
});
`;

writeFileSync(join(distDir, 'sw.js'), swSource);

console.log(`[build-sw] wrote dist/sw.js`);
console.log(`[build-sw] cache version: ${cacheVersion}`);
console.log(`[build-sw] precached ${precacheUrls.length} entries`);
